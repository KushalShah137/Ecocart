-- =============================================================================
-- EcoCart | 01_schema.sql  (run as ECOCART)
-- The ten core tables. Uses Oracle-compatible CREATE TABLE syntax (works on Oracle XE 21c+),
-- so an existing table is never dropped or recreated. If your existing tables
-- lack any of the columns used by the application, run 06_migrations.sql,
-- which adds only what is missing.
--
-- Design notes
--   * NUMBER(10,2) for money (INR), NUMBER(3) for scores/ratings.
--   * IDENTITY primary keys (no manual sequences/triggers needed).
--   * DATA_ORIGIN marks whether a row came from the ORIGINAL dataset import,
--     is SYNTHETIC demo data, or was created LIVE by the application.
-- =============================================================================

CREATE TABLE category (
  category_id    NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  category_name  VARCHAR2(80)   NOT NULL,
  slug           VARCHAR2(80)   NOT NULL,
  description    VARCHAR2(400),
  icon           VARCHAR2(40),
  created_at     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_category      PRIMARY KEY (category_id),
  CONSTRAINT uq_category_name UNIQUE (category_name),
  CONSTRAINT uq_category_slug UNIQUE (slug)
);

CREATE TABLE app_user (
  user_id        NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  full_name      VARCHAR2(120)  NOT NULL,
  email          VARCHAR2(160)  NOT NULL,
  password_hash  VARCHAR2(300)  NOT NULL,
  phone          VARCHAR2(20),
  address_line   VARCHAR2(240),
  city           VARCHAR2(80),
  state          VARCHAR2(80),
  pincode        VARCHAR2(10),
  role           VARCHAR2(20)   DEFAULT 'CUSTOMER' NOT NULL,
  is_demo        NUMBER(1)      DEFAULT 0 NOT NULL,
  data_origin    VARCHAR2(20)   DEFAULT 'LIVE' NOT NULL,
  created_at     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_app_user          PRIMARY KEY (user_id),
  CONSTRAINT uq_app_user_email    UNIQUE (email),
  CONSTRAINT ck_app_user_role     CHECK (role IN ('CUSTOMER','ADMIN')),
  CONSTRAINT ck_app_user_demo     CHECK (is_demo IN (0,1)),
  CONSTRAINT ck_app_user_origin   CHECK (data_origin IN ('ORIGINAL','SYNTHETIC','LIVE')),
  CONSTRAINT ck_app_user_email    CHECK (INSTR(email,'@') > 1)
);

CREATE TABLE product (
  product_id     NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  category_id    NUMBER(10)     NOT NULL,
  product_name   VARCHAR2(160)  NOT NULL,
  brand          VARCHAR2(80),
  description    VARCHAR2(1000),
  price          NUMBER(10,2)   NOT NULL,
  stock_quantity NUMBER(8)      DEFAULT 0 NOT NULL,
  image_url      VARCHAR2(400),
  is_active      NUMBER(1)      DEFAULT 1 NOT NULL,
  is_featured    NUMBER(1)      DEFAULT 0 NOT NULL,
  data_origin    VARCHAR2(20)   DEFAULT 'LIVE' NOT NULL,
  source_key     VARCHAR2(80),
  created_at     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_product           PRIMARY KEY (product_id),
  CONSTRAINT fk_product_category  FOREIGN KEY (category_id) REFERENCES category(category_id),
  CONSTRAINT ck_product_price     CHECK (price > 0),
  CONSTRAINT ck_product_stock     CHECK (stock_quantity >= 0),
  CONSTRAINT ck_product_active    CHECK (is_active IN (0,1)),
  CONSTRAINT ck_product_featured  CHECK (is_featured IN (0,1)),
  CONSTRAINT ck_product_origin    CHECK (data_origin IN ('ORIGINAL','SYNTHETIC','LIVE'))
);

CREATE TABLE product_sustainability (
  sustainability_id          NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  product_id                 NUMBER(10)    NOT NULL,
  material                   VARCHAR2(120) NOT NULL,
  packaging_type             VARCHAR2(80)  NOT NULL,
  recyclability_pct          NUMBER(5,2),
  eco_score                  NUMBER(3)     NOT NULL,
  carbon_footprint_kg        NUMBER(8,3),
  carbon_footprint_unit      VARCHAR2(80),
  sustainability_explanation VARCHAR2(600),
  score_source               VARCHAR2(200),
  data_origin                VARCHAR2(20)  DEFAULT 'LIVE' NOT NULL,
  updated_at                 TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_sustainability        PRIMARY KEY (sustainability_id),
  CONSTRAINT uq_sustainability_prod   UNIQUE (product_id),
  CONSTRAINT fk_sustainability_prod   FOREIGN KEY (product_id) REFERENCES product(product_id) ON DELETE CASCADE,
  CONSTRAINT ck_sustainability_score  CHECK (eco_score BETWEEN 0 AND 100),
  CONSTRAINT ck_sustainability_recyc  CHECK (recyclability_pct IS NULL OR recyclability_pct BETWEEN 0 AND 100),
  CONSTRAINT ck_sustainability_carbon CHECK (carbon_footprint_kg IS NULL OR carbon_footprint_kg >= 0),
  CONSTRAINT ck_sustainability_cunit  CHECK ((carbon_footprint_kg IS NULL AND carbon_footprint_unit IS NULL)
                                             OR (carbon_footprint_kg IS NOT NULL AND carbon_footprint_unit IS NOT NULL)),
  CONSTRAINT ck_sustainability_origin CHECK (data_origin IN ('ORIGINAL','SYNTHETIC','LIVE'))
);

CREATE TABLE cart (
  cart_id        NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  user_id        NUMBER(10)     NOT NULL,
  status         VARCHAR2(20)   DEFAULT 'ACTIVE' NOT NULL,
  created_at     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_cart         PRIMARY KEY (cart_id),
  CONSTRAINT fk_cart_user    FOREIGN KEY (user_id) REFERENCES app_user(user_id),
  CONSTRAINT ck_cart_status  CHECK (status IN ('ACTIVE','CHECKED_OUT','ABANDONED'))
);

CREATE TABLE cart_item (
  cart_item_id   NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  cart_id        NUMBER(10)     NOT NULL,
  product_id     NUMBER(10)     NOT NULL,
  quantity       NUMBER(5)      NOT NULL,
  added_at       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_cart_item          PRIMARY KEY (cart_item_id),
  CONSTRAINT fk_cart_item_cart     FOREIGN KEY (cart_id) REFERENCES cart(cart_id) ON DELETE CASCADE,
  CONSTRAINT fk_cart_item_product  FOREIGN KEY (product_id) REFERENCES product(product_id),
  CONSTRAINT uq_cart_item          UNIQUE (cart_id, product_id),
  CONSTRAINT ck_cart_item_qty      CHECK (quantity BETWEEN 1 AND 50)
);

CREATE TABLE customer_order (
  order_id         NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  order_ref        VARCHAR2(30)   NOT NULL,
  user_id          NUMBER(10)     NOT NULL,
  order_date       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  status           VARCHAR2(20)   DEFAULT 'PLACED' NOT NULL,
  subtotal         NUMBER(12,2)   NOT NULL,
  shipping_fee     NUMBER(10,2)   DEFAULT 0 NOT NULL,
  total_amount     NUMBER(12,2)   NOT NULL,
  shipping_address VARCHAR2(400),
  data_origin      VARCHAR2(20)   DEFAULT 'LIVE' NOT NULL,
  source_key       VARCHAR2(80),
  CONSTRAINT pk_customer_order       PRIMARY KEY (order_id),
  CONSTRAINT uq_customer_order_ref   UNIQUE (order_ref),
  CONSTRAINT fk_customer_order_user  FOREIGN KEY (user_id) REFERENCES app_user(user_id),
  CONSTRAINT ck_customer_order_stat  CHECK (status IN ('PLACED','CONFIRMED','SHIPPED','DELIVERED','CANCELLED')),
  CONSTRAINT ck_customer_order_amt   CHECK (subtotal >= 0 AND shipping_fee >= 0 AND total_amount = subtotal + shipping_fee),
  CONSTRAINT ck_customer_order_orig  CHECK (data_origin IN ('ORIGINAL','SYNTHETIC','LIVE'))
);

CREATE TABLE order_item (
  order_item_id  NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  order_id       NUMBER(10)     NOT NULL,
  product_id     NUMBER(10)     NOT NULL,
  quantity       NUMBER(5)      NOT NULL,
  unit_price     NUMBER(10,2)   NOT NULL,   -- purchase-time price (never re-read from PRODUCT)
  line_total     NUMBER(12,2)   NOT NULL,
  CONSTRAINT pk_order_item          PRIMARY KEY (order_item_id),
  CONSTRAINT fk_order_item_order    FOREIGN KEY (order_id) REFERENCES customer_order(order_id) ON DELETE CASCADE,
  CONSTRAINT fk_order_item_product  FOREIGN KEY (product_id) REFERENCES product(product_id),
  CONSTRAINT uq_order_item          UNIQUE (order_id, product_id),
  CONSTRAINT ck_order_item_qty      CHECK (quantity > 0),
  CONSTRAINT ck_order_item_price    CHECK (unit_price >= 0),
  CONSTRAINT ck_order_item_total    CHECK (line_total = quantity * unit_price)
);

CREATE TABLE payment (
  payment_id      NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  order_id        NUMBER(10)     NOT NULL,
  payment_method  VARCHAR2(30)   NOT NULL,
  amount          NUMBER(12,2)   NOT NULL,
  status          VARCHAR2(20)   DEFAULT 'PENDING' NOT NULL,
  transaction_ref VARCHAR2(60),
  paid_at         TIMESTAMP,
  created_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_payment          PRIMARY KEY (payment_id),
  CONSTRAINT uq_payment_order    UNIQUE (order_id),           -- one payment record per order: no duplicate payments
  CONSTRAINT fk_payment_order    FOREIGN KEY (order_id) REFERENCES customer_order(order_id) ON DELETE CASCADE,
  CONSTRAINT ck_payment_method   CHECK (payment_method IN ('COD','DEMO_UPI','DEMO_CARD','DEMO_WALLET')),
  CONSTRAINT ck_payment_status   CHECK (status IN ('PENDING','PAID','FAILED','REFUNDED')),
  CONSTRAINT ck_payment_amount   CHECK (amount >= 0)
);

CREATE TABLE review (
  review_id    NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  product_id   NUMBER(10)     NOT NULL,
  user_id      NUMBER(10)     NOT NULL,
  rating       NUMBER(1)      NOT NULL,
  title        VARCHAR2(120),
  review_text  VARCHAR2(1000),
  is_verified  NUMBER(1)      DEFAULT 0 NOT NULL,
  data_origin  VARCHAR2(20)   DEFAULT 'LIVE' NOT NULL,
  created_at   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_review          PRIMARY KEY (review_id),
  CONSTRAINT fk_review_product  FOREIGN KEY (product_id) REFERENCES product(product_id) ON DELETE CASCADE,
  CONSTRAINT fk_review_user     FOREIGN KEY (user_id) REFERENCES app_user(user_id),
  CONSTRAINT uq_review_user_prod UNIQUE (product_id, user_id),  -- review policy: one review per customer per product
  CONSTRAINT ck_review_rating   CHECK (rating BETWEEN 1 AND 5),
  CONSTRAINT ck_review_verified CHECK (is_verified IN (0,1)),
  CONSTRAINT ck_review_origin   CHECK (data_origin IN ('ORIGINAL','SYNTHETIC','LIVE'))
);

COMMENT ON TABLE product_sustainability IS 'Eco-Score 0-100 computed by the documented EcoCart methodology (see README). DATA_ORIGIN=SYNTHETIC rows are demo estimates, not certified measurements.';
COMMENT ON COLUMN order_item.unit_price IS 'Price captured at purchase time; independent of later PRODUCT.price changes.';
COMMENT ON COLUMN customer_order.data_origin IS 'ORIGINAL = imported dataset row, SYNTHETIC = generated demo row, LIVE = placed through the website.';
